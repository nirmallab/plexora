"""The website's envelope as one page: docs/internal/bench/envelope/ENVELOPE.md.

    python tools/bench_envelope/envelope_table.py            # write ENVELOPE.md
    python tools/bench_envelope/envelope_table.py --check    # exit 1 if it is stale
    python tools/bench_envelope/envelope_table.py add <file> --label <computer>

Two sources, both in the repository:

- the limits the website decides with (plexora/client/src/envelope.json),
  each with the measurement it came from;
- the self-check records (docs/internal/bench/envelope/selfcheck/*.json): the
  file the website's /selfcheck page saves (client services/selfcheck.js),
  one per computer and browser, sent by whoever ran it. Each carries the
  website's estimate for that computer, made from its cores and memory before
  measuring, beside the measurement -- so the page shows how good the
  estimate was where it matters, on computers this machine is not.

`add` checks a downloaded file is a self-check record whose every step was
measured, and files it as `<date>-<label>.json`; then the page is written
again.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIMITS = ROOT / "plexora" / "client" / "src" / "envelope.json"
FOLDER = ROOT / "docs" / "internal" / "bench" / "envelope"
RECORDS = FOLDER / "selfcheck"
PAGE = FOLDER / "ENVELOPE.md"
STEPS = ("browser", "storage", "download", "python", "pyramid", "memory", "gpu")


def _gb(value) -> str:
    return "—" if not value else f"{value / 1e9:.0f}" if value >= 10e9 else f"{value / 1e9:.1f}"


def _s(ms) -> str:
    return "—" if ms is None else f"{ms / 1000:.1f}"


def records() -> list[tuple[str, dict]]:
    found = []
    for path in sorted(RECORDS.glob("*.json")):
        try:
            found.append((path.stem, json.loads(path.read_text(encoding="utf-8"))))
        except (OSError, json.JSONDecodeError):
            continue
    return found


def _row(label: str, record: dict) -> str:
    steps = record.get("steps") or {}
    detail = lambda name: (steps.get(name) or {}).get("detail") or {}  # noqa: E731
    browser, download, python = detail("browser"), detail("download"), detail("python")
    pyramid, memory, gpu = detail("pyramid"), detail("memory"), detail("gpu")
    estimate = (pyramid.get("estimate") or {}).get("flat_limit_bytes")
    measured = (pyramid.get("measured") or {}).get("flat_limit_bytes")
    ratio = f"{measured / estimate:.2f}" if estimate and measured else "—"
    memory_gb = browser.get("memory_gb")
    cells = [
        label,
        str(browser.get("engine") or "—"),
        str(browser.get("platform") or "—"),
        f"{browser.get('cores') or '—'} / {('8+' if (memory_gb or 0) >= 8 else memory_gb) or '—'}",
        f"{download.get('bytes_per_second', 0) / 1e6:.1f}" if download.get("bytes_per_second") else "—",
        _s(python.get("page_ms")),
        f"{pyramid.get('bytes_per_second', 0) / 1e6:.0f}" if pyramid.get("bytes_per_second") else "—",
        f"{_gb(measured)} ({_gb(estimate)}, ×{ratio})",
        _gb(memory.get("wasm_bytes")),
        f"{(memory.get('table_values_here') or 0) / 1e6:.0f} M" if memory.get("table_values_here") else "—",
        "yes" if gpu.get("webgpu") else "no",
        "" if record.get("ok") else "not every step",
    ]
    return "| " + " | ".join(cells) + " |"


def page() -> str:
    limits = json.loads(LIMITS.read_text(encoding="utf-8"))
    lines = [
        "# The website's envelope",
        "",
        "Generated by `tools/bench_envelope/envelope_table.py` from `plexora/client/src/envelope.json`",
        "and the self-check records in `selfcheck/`; do not edit by hand. The website decides with the",
        "limits below (client services/handoffNotice.js); the self-check page (`/selfcheck`) measures a",
        "computer against them.",
        "",
        "## The limits",
        "",
        "| Limit | Values | Measured |",
        "|---|---|---|",
    ]
    for name, section in limits.items():
        if not isinstance(section, dict):
            continue
        values = ", ".join(f"`{key}` {json.dumps(value)}" for key, value in section.items() if key != "measured")
        lines.append(f"| {name} | {values} | {section.get('measured') or limits.get('measured') or '—'} |")
    lines += [
        "",
        "## Computers (self-check records)",
        "",
        "Flat limit: the flat image the website builds within its time limit there, from the measured",
        "build rate scaled by the reference computer's own run (`selfcheck` above); in brackets the",
        "estimate from its cores, and measured over estimated. Tables: the website's limit there (by",
        "the device's memory).",
        "",
        "| Record | Browser | Platform | Cores / GB | Download MB/s | Python ready s | Pyramid MB/s "
        "| Flat limit GB (estimate, ×) | Wasm GB | Tables | WebGPU | |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    rows = [_row(label, record) for label, record in records()]
    lines += rows or ["| (none yet) | | | | | | | | | | | |"]
    return "\n".join(lines) + "\n"


def add(source: Path, label: str) -> Path:
    record = json.loads(Path(source).read_text(encoding="utf-8"))
    if record.get("selfcheck") != 1 or not isinstance(record.get("steps"), dict):
        raise SystemExit(f"{source}: not a self-check record")
    missing = [name for name in STEPS if not (record["steps"].get(name) or {}).get("ok")]
    if missing:
        print(f"note: not measured there: {', '.join(missing)}", file=sys.stderr)
    slug = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
    if not slug:
        raise SystemExit("--label names the computer, e.g. mac-safari")
    RECORDS.mkdir(parents=True, exist_ok=True)
    target = RECORDS / f"{str(record.get('date', ''))[:10]}-{slug}.json"
    shutil.copyfile(source, target)
    return target


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("command", nargs="?", choices=("write", "add"), default="write")
    parser.add_argument("file", nargs="?", help="add: the downloaded self-check file")
    parser.add_argument("--label", help="add: the computer and browser, e.g. mac-safari")
    parser.add_argument("--check", action="store_true", help="exit 1 if ENVELOPE.md is not up to date")
    args = parser.parse_args(argv)
    if args.command == "add":
        if not args.file or not args.label:
            parser.error("add needs the file and --label")
        print(add(Path(args.file), args.label))
    text = page()
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != text:
            print(f"{PAGE} is out of date: run tools/bench_envelope/envelope_table.py", file=sys.stderr)
            return 1
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    print(PAGE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
