#!/usr/bin/env python
"""Keep the website's price list in step with what the BioCognia platform charges.

Plexora's prices belong to the BioCognia platform: plans and prices are edited
there, and only there, and ``GET /v1/products/plexora`` publishes them. The
website is a static export and cannot ask the platform at build time, so it
reads a checked-in copy, ``website/data/pricebook.json``, which the pricing
page draws from. This tool is the only thing that should write that copy.

    python tools/sync_pricing.py --source             # fetch from the platform, write
    python tools/sync_pricing.py --source --check     # fail if the copy has drifted
    python tools/sync_pricing.py --source product.json  # the same, from a saved record
    python tools/sync_pricing.py --check              # offline: validate the copy

Without ``--source`` nothing is fetched: the checked-in copy is validated (one
flat price per seat in every tier, the introductory price never above the
standard one) and re-rendered. That is what CI runs, because CI has no business
depending on a network call. With ``--source`` the platform's product record is
converted into the website's shape and written (or, with ``--check``, compared).

Plexora Pro has one price per seat per year for each use class: the total is
that price times the seats, and a subscription renews at the price it was
bought at. So the platform must publish exactly one row per use class the
website shows, for one seat upward (``seats_min`` 1, ``seats_max`` null). Seat
brackets, or two rows for one use class, are refused rather than flattened:
which of them the page should quote is not this tool's decision.

The conversion takes only the *numbers* from the platform -- intro and standard
price per seat, by use class, and the AI credits each seat includes. The words
around them (tier names, the notes) are the website's and come from the
checked-in copy. A use class the copy does not describe (nonprofit, say) is
left out and said so: adding one is a decision about how the page presents it,
so it is made by editing the copy, after which this tool keeps the numbers
right.

SCIMAP Pro's ``tools/syncPricing.py`` is the same tool for its own site.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "website" / "data" / "pricebook.json"

PLATFORM_URL = "https://api.biocognia.com/v1/products/plexora"
PRODUCT_ID = "plexora"
DEFAULT_PLAN = "plexora.pro"
TIMEOUT_SECONDS = 10
#: The platform counts AI credits in micro-units: one credit is one US cent.
MICRO_PER_CREDIT = 10_000
#: The pricebook shape this tool writes and accepts: one flat price per tier.
VERSION = 2

COMMENT = (
    "Generated by tools/sync_pricing.py. Plexora's prices are edited on the "
    "BioCognia platform (GET https://api.biocognia.com/v1/products/plexora); "
    "this is the website's copy of them. Edit the words here if you must, never "
    "the numbers: run `tools/sync_pricing.py --source` to refresh those."
)


class PricingError(ValueError):
    """The price list is inconsistent, or cannot be mapped onto the website's."""


# ---------------------------------------------------------------------------
# Reading
# ---------------------------------------------------------------------------

def load(path: pathlib.Path = TARGET) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def fetch_product(source: str) -> dict:
    """The platform's product record, from a URL or a saved JSON file."""
    if source.startswith(("https://", "http://")):
        request = urllib.request.Request(source, headers={
            "Accept": "application/json",
            # Every request to the platform names its client (design B8).
            "BioCognia-Client": "plexora/sync_pricing",
            # Cloudflare refuses urllib's default User-Agent (error 1010).
            "User-Agent": "plexora/sync_pricing",
        })
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            return json.loads(response.read().decode("utf-8"))
    return json.loads(pathlib.Path(source).read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# Converting
# ---------------------------------------------------------------------------

def _plan_id(record: dict, plan: str | None) -> str:
    """The plan whose prices the pricing page shows."""
    if plan:
        return plan
    ids = {price.get("plan_id") for price in record.get("prices", [])}
    if DEFAULT_PLAN in ids:
        return DEFAULT_PLAN
    seat_plans = [
        p["id"] for p in record.get("plans", [])
        if p.get("seat_model", "seat") == "seat" and not p.get("add_on") and p["id"] in ids
    ]
    if len(seat_plans) == 1:
        return seat_plans[0]
    raise PricingError(
        f"Cannot tell which plan the website should show (priced plans: {sorted(map(str, ids))}). "
        "Pass --plan."
    )


def from_product(record: dict, base: dict, plan: str | None = None) -> tuple[dict, list[str]]:
    """The website pricebook for ``record``, worded like ``base``.

    Returns the book and a list of notes about platform prices that were
    deliberately left out (use classes or terms the website does not show).
    """
    if record.get("id") != PRODUCT_ID:
        raise PricingError(f"Expected the {PRODUCT_ID!r} product record, got {record.get('id')!r}.")
    plan_id = _plan_id(record, plan)
    rows = [p for p in record.get("prices", []) if p.get("plan_id") == plan_id]
    if not rows:
        raise PricingError(f"The platform has no prices for plan {plan_id!r}.")

    currency = base["currency"]
    notes: list[str] = []
    book = json.loads(json.dumps(base))  # a deep copy; the words carry over
    book["_comment"] = COMMENT
    audiences = {tier["audience"]: key for key, tier in book["seatTiers"].items()}

    seen: dict[str, dict] = {}
    for row in rows:
        use_class = row.get("use_class")
        tier_key = audiences.get(use_class)
        if tier_key is None:
            notes.append(f"{use_class} prices are on the platform but not on the website; left out.")
            continue
        tier = book["seatTiers"][tier_key]
        if row.get("term_days", 365) != tier["termDays"]:
            notes.append(f"{use_class} has a {row.get('term_days')}-day price; the website shows "
                         f"{tier['termDays']}-day terms only, so it was left out.")
            continue
        if row.get("currency", currency) != currency:
            raise PricingError(f"{use_class} is priced in {row.get('currency')}, the website in {currency}.")

        low, high = row.get("seats_min", 1), row.get("seats_max")
        if low not in (None, 1) or high is not None:
            raise PricingError(
                f"The platform prices {use_class} for {low}-{high if high is not None else 'any'} seats: "
                "seat brackets, which Plexora Pro no longer has. The website shows one price per seat "
                "from one seat upward (seats_min 1, seats_max null); fix the platform's price rows "
                "for this plan and run this again."
            )
        if tier_key in seen:
            raise PricingError(
                f"Two platform prices for {use_class} on plan {plan_id!r}; there must be exactly one."
            )
        standard = int(row["standard_cents"])
        intro = row.get("intro_cents")
        seen[tier_key] = {"introCents": standard if intro is None else int(intro), "standardCents": standard}

    for tier_key, tier in book["seatTiers"].items():
        price = seen.get(tier_key)
        if price is None:
            raise PricingError(f"The platform has no {tier['audience']} price on plan {plan_id!r}.")
        tier["price"] = price

    # The AI credits a seat includes each year, which the page states beside the price.
    plan_row = next((p for p in record.get("plans", []) if p.get("id") == plan_id), None)
    micro = None if plan_row is None else plan_row.get("credits_micro")
    if micro is None or int(micro) <= 0 or int(micro) % MICRO_PER_CREDIT:
        raise PricingError(
            f"Plan {plan_id!r} includes {micro!r} micro-credits; the page needs a positive whole "
            "number of AI credits per seat."
        )
    book["notes"]["creditsPerSeat"] = int(micro) // MICRO_PER_CREDIT

    validate(book)
    return book, notes


# ---------------------------------------------------------------------------
# Checking
# ---------------------------------------------------------------------------

def validate(book: dict) -> None:
    """Refuse a price list the page cannot draw honestly."""
    if book.get("version") != VERSION:
        raise PricingError(
            f"The pricebook is version {book.get('version')!r}; this tool reads version {VERSION} "
            "(one flat price per seat, no brackets)."
        )
    if "brackets" in book:
        raise PricingError("The pricebook has seat brackets; Plexora Pro has one price per seat.")
    tiers = book.get("seatTiers") or {}
    if not tiers:
        raise PricingError("The pricebook has no seat tiers.")
    audiences = [tier.get("audience") for tier in tiers.values()]
    if len(set(audiences)) != len(audiences):
        raise PricingError(f"Two seat tiers share a use class: {audiences}.")
    for name, tier in tiers.items():
        if "prices" in tier:
            raise PricingError(f"{name} is priced by bracket ('prices'); version {VERSION} has one 'price'.")
        price = tier.get("price")
        if not isinstance(price, dict):
            raise PricingError(f"{name} has no price.")
        intro, standard = price.get("introCents"), price.get("standardCents")
        if not all(isinstance(cents, int) and cents > 0 for cents in (intro, standard)):
            raise PricingError(f"{name}: prices must be a positive whole number of cents.")
        if intro > standard:
            raise PricingError(f"{name}: the introductory price is above the standard one.")
    credits = book.get("notes", {}).get("creditsPerSeat")
    if not isinstance(credits, int) or isinstance(credits, bool) or credits <= 0:
        raise PricingError("notes.creditsPerSeat must be a positive whole number of AI credits.")


def render(book: dict) -> str:
    book = {"_comment": COMMENT, **{k: v for k, v in book.items() if k != "_comment"}}
    return json.dumps(book, indent=2, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------------------
# The command
# ---------------------------------------------------------------------------

def main(argv=None, target: pathlib.Path = TARGET) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", nargs="?", const=PLATFORM_URL, default=None,
                        metavar="URL_OR_FILE",
                        help=f"the platform's product record (default with no value: {PLATFORM_URL})")
    parser.add_argument("--plan", default=None,
                        help=f"which platform plan the website shows (default: {DEFAULT_PLAN})")
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the website copy is out of date")
    args = parser.parse_args(argv)

    if not target.exists():
        print(f"{target} not found.", file=sys.stderr)
        return 1
    current_text = target.read_text(encoding="utf-8")
    base = json.loads(current_text)

    try:
        if args.source:
            try:
                record = fetch_product(args.source)
            except (OSError, ValueError) as error:
                print(f"Could not read the product record from {args.source}: {error}", file=sys.stderr)
                return 2
            book, notes = from_product(record, base, args.plan)
            for note in notes:
                print(note, file=sys.stderr)
        else:
            book = base
            validate(book)
    except PricingError as error:
        print(str(error), file=sys.stderr)
        return 1

    text = render(book)
    shown = target.relative_to(ROOT) if target.is_relative_to(ROOT) else target
    if args.check:
        if current_text != text:
            again = "    python tools/sync_pricing.py" + (" --source" if args.source else "")
            print(f"{shown} is stale. Run:\n{again}", file=sys.stderr)
            return 1
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"Wrote {shown}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
