def edit_project_page(name=None):
    name = name or request.args.get('config')
    project = Project.find(name) if name else None
    if project is None:
        return redirect(f"{_base_url()}/open_project")

    return render_template('project_edit.html', data=template_data(
        datasetName=name,
        project=_describe(project),
        needs=_needs_for_tool(project, request.args.get('needs')),
    ))


def known_layers(project):
    """The project with `dataset.layers` filled in, reading the file when they
    were never recorded.

    In memory only -- nothing is written back, so this is safe on the GET paths
    that render a picker. Shared with tool_routes, which needs the same list to
    put the matrix question in the requirements modal: without the backfill, a
    project imported before layers were recorded would be offered a choice of
    one, which is exactly the project that most needs the choice.
    """
    if project.dataset and not project.dataset.layers:
        return project.with_layers(source_layers(project.dataset))
    return project


def known_obsm(project):
    """The project with `dataset.obsm` filled in, reading the file when it was
    never recorded.

    Exactly `known_layers`' job for the coordinate question, and needed more
    urgently: a project imported before obsm was recorded had its coordinate
    source chosen by a name heuristic and offers no way to see, let alone
    correct, what was chosen.
    """
    if project.dataset and not project.dataset.obsm:
        return project.with_obsm(source_obsm(project.dataset))
    return project


def _describe(project):
    """The project as the edit page and the requirements modal consume it.

    Deliberately not the raw entry: the page renders sections from `has`, so
    what it asks about is decided here, once, from the record -- rather than by
    a template guessing which fields might apply to which kind of project.
    """
    project = known_obsm(known_layers(project))
    spec = project.dataset
    layers = list(spec.layers) if spec else []
    return {
        "name": project.name,
        # Every layer this sample draws, the reference and the mask included.
        # `manifest.layers` rather than a second walk of `all_layers` here, so
        # the edit page and a plugin asking the same question get the same
        # answer.
        "layers": manifest.layers(project),
        "image": {
            "src": project.image.src,
            "kind": project.image.kind,
            "channelCount": project.image.num_channels,
            "size": [project.image.width, project.image.height],
            # True when there is no image file behind this sample at all. The
            # edit page reads it to say so rather than printing an empty path,
            # and to keep the Scale section -- which is the one control on that
            # page a blank frame genuinely has, because its micron-per-pixel is
            # what every layer registered against it was scaled by.
            "blank": project.image.is_blank,
        },
        # The same split the cell layer makes, for the same reason. `imageType`
        # is how the image is actually being read and is what the select shows;
        # `imageTypeChoice` is whether that was a decision or the detector's
        # default. `imageTypeReason` is the detector's own sentence, shown next
        # to the Automatic option so the user can tell whether overriding it is
        # warranted -- absent for a project imported before any of this existed.
        "imageType": project.image_type,
        "imageTypeChoice": project.image.image_type_choice,
        "imageTypeDetected": project.image.image_type_detected,
        "imageTypeReason": project.image.image_type_reason,
        "segmentation": {
            # The node address when the mask is on one, because this is the
            # value the field posts back: showing a blank here would make
            # saving an unrelated setting read as "the user cleared the mask".
            "src": _segmentation_field(project),
            "available": project.segmentation.available,
            "pending": project.segmentation.pending,
            "mode": project.segmentation.mode,
        },
        "data": None if spec is None else {
            "type": spec.type,
            "src": spec.src,
            "table": spec.table,
            "coordinates": dict(spec.coordinates),
            "features": dict(spec.features),
            "subset": dict(spec.subset),
            "isTransformed": spec.is_transformed,
            "layers": layers,
            # What this source still needs before it can be read -- empty for
            # almost every project. The Data field inspects on mount when it is
            # not, so the table select arrives already populated rather than
            # only after the user retypes a path they already gave.
            "unresolved": list(spec.unresolved),
        },
        # Which matrix the intensities are read from, in the same "X" /
        # "layer:<name>" vocabulary the import form's picker uses, plus whether
        # they are log1p'd on the way in. Two halves of one question -- what
        # numbers is this project actually showing.
        "featureSource": project.feature_source,
        "featureOptions": project.feature_options,
        "featureLog": project.log_transformed,
        # Both, because they are different facts. `cellLayer` is what the
        # project resolves to and is what the select shows; `cellLayerChoice`
        # is whether that was a decision or a default, which is the difference
        # between a form the user can leave alone and one that records an
        # override every time it is saved.
        "cellLayer": project.cell_layer,
        "cellLayerChoice": project.cell_layer_choice,
        "cellLayerOptions": project.cell_layer_options,
        "roles": project.roles.to_dict(),
        "roleLabels": dict(ROLE_LABELS),
        # The role selects, in the vocabulary the question is asked in -- obs
        # columns for AnnData and SpatialData, table columns for a CSV. See
        # Project.role_columns; this page and the requirements modal render
        # from the same three keys so they cannot drift.
        "roleColumns": project.role_columns,
        "roleAnswers": project.role_answers,
        "roleDefaults": project.role_defaults,
        # The coordinate question's own material: every obsm array with its
        # shape, every obs column, and the source recorded now. Separate from
        # the role keys because its answer is a read spec rather than a column
        # name -- an obsm array supplies both axes at once.
        "coordinateOptions": project.coordinate_options,
        "singleImage": bool(spec and spec.single_image),
        "rowNumberIds": bool(spec and spec.row_number_ids),
        "editableRoles": _editable_roles(project),
        "columns": {
            "markers": list(project.columns.markers),
            "metadata": list(project.columns.metadata),
        },
        # Which sections the page renders. A project with only an image has no
        # roles to assign and no columns to classify, so it is not shown empty
        # controls for them.
        # Where each of the three scientific resources is served from. Present
        # for every project, and all-local for almost all of them -- the page
        # renders the section either way, because "this is on this machine" is
        # a fact worth stating once somewhere else is possible at all.
        "resources": _resource_view(project),
        # Every question core can record an answer to, with whether it was
        # answered or guessed. The page does not render from this yet; it is
        # here because the edit page, the requirements modal, the project card
        # and the CLI all used to work "does this project have a table?" out
        # separately, and every `has` boolean below is now one read of it.
        "manifest": manifest.manifest(project),
        "summary": manifest.summary(project),
        "has": {
            # A file the user named, readable or not -- the Data SECTION shows
            # for both, since an unresolved source is precisely the project
            # whose path needs to be visible and editable.
            "dataSource": project.has_data_source,
            "data": manifest.answered(project, "table"),
            "columns": project.has_table and is_flat_table(spec.type),
            "readSpec": project.has_table and spec.type in ("anndata", "spatialdata"),
            "segmentation": manifest.answered(project, "segmentation"),
            # Any project with a table. The matrix select needs more than one
            # matrix to be worth showing -- the template guards it on
            # `data.layers`, so a CSV gets the log switch alone -- but that
            # switch is a real question for every format: whether the numbers
            # are raw counts is not something the file says, and a CSV of raw
            # counts is the commonest case of all. This used to be restricted
            # to the formats that state their own marker split, which left CSV
            # projects with no way to reach the transform at all.
            "features": project.has_table,
            # Offered only once there is something to choose between: a project
            # with neither a mask nor coordinates cannot draw cells at all.
            "cellLayer": bool(project.cell_layer_options),
        },
    }


def _segmentation_field(project):
    """What the edit page's Segmentation Mask field shows, and posts back.

    A local mask shows its source path. One on a node shows `node://…`, which
    is the same vocabulary the import form's fields take -- so the field is
    round-trippable for both, and `_apply_edit` can tell "unchanged" from "the
    user cleared it" without consulting the binding a second time.
    """
    from plexora.server.providers.base import node_locator

    binding = project.resource("segmentation")
    if binding is not None:
        return node_locator(binding.node, binding.resource_id)
    return project.segmentation.source


#: What each resource is called on the edit page, and the local path to show
#: when it is here. One table rather than three branches, so the section cannot
#: come to describe one resource in different words from another.
_RESOURCE_LABELS = {
    "image": "Image",
    "segmentation": "Segmentation mask",
    "table": "Cell table",
}


def _resource_view(project):
    """Where this project's image, mask and table are served from.

    Reads the project record only -- no node is contacted. Whether a node is
    ANSWERING is a different question with a different lifetime, and it is
    asked by the Settings page and by the controls that need it; putting it
    here would make opening an edit page wait on a sleeping laptop.
    """
    from plexora.server.models.project import RESOURCE_KINDS

    paths = {
        "image": project.image.src,
        "segmentation": project.segmentation.derived or project.segmentation.source,
        "table": project.dataset.src if project.dataset else None,
    }
    present = {
        # A blank frame has no bytes anywhere, so it is not a resource this
        # section can show a path for or repoint at a node -- and offering a
        # row for it would invite the user to fix something that is not broken.
        "image": ((bool(project.image.src) and not project.image.is_blank)
                  or "image" in project.resources),
        "segmentation": project.segmentation.requested or "segmentation" in project.resources,
        # The FILE, not a readable table: this section is about where bytes
        # come from, and a store whose table is undecided is still a file
        # sitting on this machine or on a node.
        "table": project.has_data_source,
    }
    view = []
    for kind in RESOURCE_KINDS:
        binding = project.resources.get(kind)
        view.append({
            "kind": kind,
            "label": _RESOURCE_LABELS[kind],
            "present": present[kind],
            "provider": "node" if binding is not None else "local",
            "node": binding.node if binding is not None else None,
            "resourceId": binding.resource_id if binding is not None else None,
            "path": None if binding is not None else paths[kind],
        })
    return view


