@app.route('/project/<string:name>/layers/<path:layer_id>', methods=['DELETE'])
def project_remove_layer(name, layer_id):
    """Stop drawing one registered layer.

    The registration only. The file it was read from is the user's and Plexora
    never owned it -- it opened it and remembered where it was -- so removing a
    layer from a sample must not be capable of deleting anybody's data. Derived
    artefacts built FROM it (a transcript tile cache) are Plexora's own and are
    left in place too: re-adding the layer then costs nothing, and a directory
    of caches is cheap next to re-reading a 6 GB parquet.

    The synthesized ids are refused rather than silently ignored: the way to
    remove the mask is to clear the mask field, and an X that quietly did
    nothing would be worse than no X.
    """
    from plexora.server.models.project import RESERVED_LAYER_IDS

    if layer_id in RESERVED_LAYER_IDS:
        return jsonify(error=f"{layer_id} is drawn from the project itself. "
                             "Remove what it is made of instead."), 400
    project = Project.find(name)
    if project is None:
        return jsonify(error=f"Unknown project: {name!r}"), 404
    if project.layer(layer_id) is None:
        return jsonify(error=f"{name} has no layer {layer_id!r}"), 404
    Project.mutate(name, lambda current: current.without_layer(layer_id))
    return jsonify(success=True, layer=layer_id)


@app.route('/project/<string:name>/layers/order', methods=['PUT'])
def project_order_layers(name):
    """Restack this project's registered layers, bottom of the stack first.

    Its own route, and ahead of the PATCH below so a layer that happens to be
    called `order` cannot shadow it: Flask matches in registration order and
    `<path:layer_id>` would otherwise swallow this.

    Order is stored because it is a statement about the sample -- which slide
    is on top of which -- and not about this browser tab. It survives a reload
    for the same reason a registration does.

    The reference image may be named here along with the rest, and it is the
    only synthesized layer that may: which image was imported first should not
    decide which one can be drawn on top. What is kept for it is a depth rather
    than a position -- see `Project.with_layer_order`. The mask and the
    centroids are still placed by `all_layers` every time it is read, because
    where those composite is a fact about the viewer rather than a choice.
    """
    project = Project.find(name)
    if project is None:
        return jsonify(error=f"Unknown project: {name!r}"), 404
    payload = request.get_json(silent=True) or {}
    ids = payload.get('ids')
    if not isinstance(ids, list):
        return jsonify(error="`ids` must be a list of layer ids, bottom first."), 400
    try:
        Project.mutate(name, lambda current: current.with_layer_order(ids))
    except ValueError as error:
        return jsonify(error=str(error)), 400
    saved = Project.find(name)
    return jsonify(success=True,
                   ids=[layer.id for layer in saved.spatial_layers],
                   imageDepth=saved.image_depth)


@app.route('/project/<string:name>/layers/<path:layer_id>', methods=['PATCH'])
def project_update_layer(name, layer_id):
    """How one registered layer is drawn: shown or hidden, and its `render`.

    `render` is the per-kind presentation bag the server never acts on -- the
    opacity, the channel list, the colours and their contrast windows. Merged
    rather than replaced, so a card changing the colour does not silently drop
    the window it was not asked about; `null` for a key removes it, which is
    how "use the file's own" is said.

    Stored because these are statements about the sample rather than about
    this tab. The Layers panel wrote all of them into memory and none of them
    anywhere, so every choice survived exactly until a reload -- a control
    that works and then quietly forgets is worse than one that refuses.

    THE REFERENCE IMAGE accepts a `render` and nothing else. It is synthesized
    from `ImageSpec` rather than stored, so what arrives here is kept beside
    the project as `imageRender` and handed back out by `reference_layer`. Its
    `visible` is not stored: an eye is about this tab, and the image is the one
    layer whose absence leaves the viewer with no world at all.

    The mask and the centroids are still refused, as DELETE refuses them: the
    mask's opacity is the Cells footer's, and storing one here would be a
    second answer that nothing reads.
    """
    from plexora.server.models.project import (REFERENCE_LAYER_ID,
                                               RESERVED_LAYER_IDS)

    if layer_id in RESERVED_LAYER_IDS and layer_id != REFERENCE_LAYER_ID:
        return jsonify(error=f"{layer_id} is drawn from the project itself. "
                             "How it is drawn is not stored with it."), 400
    project = Project.find(name)
    if project is None:
        return jsonify(error=f"Unknown project: {name!r}"), 404
    existing = project.layer(layer_id)
    if existing is None:
        return jsonify(error=f"{name} has no layer {layer_id!r}"), 404

    payload = request.get_json(silent=True) or {}
    changes = {}
    if 'visible' in payload:
        changes['visible'] = payload['visible'] is not False
    if 'render' in payload:
        patch = payload['render']
        if not isinstance(patch, dict):
            return jsonify(error="`render` must be an object."), 400
        merged = dict(existing.render)
        for key, value in patch.items():
            if value is None:
                merged.pop(key, None)
            else:
                merged[key] = value
        changes['render'] = merged
    if not changes:
        return jsonify(error="Nothing to change: send `visible` or `render`."), 400

    if layer_id == REFERENCE_LAYER_ID:
        if 'render' not in changes:
            return jsonify(error="The reference image stores `render` only."), 400
        # Without `imageKind`, which `reference_layer` puts back on every read
        # off the file itself. Storing it would freeze today's answer into the
        # config and outlive a re-import that corrected it.
        merged = {key: value for key, value in changes['render'].items()
                  if key != 'imageKind'}
        Project.mutate(name, lambda current: current.patch(image_render=merged))
    else:
        Project.mutate(name, lambda current: current.with_layer(
            replace(current.layer(layer_id), **changes)))
    return jsonify(success=True, layer=Project.find(name).layer(layer_id).to_entry())


@app.route('/project/<string:name>/resources')
def project_resources(name):
    """This project's resource bindings, and what the registered nodes offer.

    One request because it is one question -- "where could this come from" --
    and the controls need both halves at once. Nodes are probed in parallel
    with each other only in the sense that one failing does not stop the rest:
    a node that is asleep is listed as unreachable rather than omitted, since
    a project may well be pointing at it and the page has to be able to say so.
    """
    from plexora.server.models import nodes as node_registry
    from plexora.server.providers import http as node_http

    project = Project.find(name)
    if project is None:
        return jsonify(error="Unknown project"), 404

    offered = []
    for node in node_registry.load_all().values():
        try:
            hello = node_http.hello(node, timeout=2.5)
            offered.append({
                "name": node.name, "reachable": True,
                "resources": hello.get("resources") or [],
                "capabilities": hello.get("capabilities") or [],
            })
        except Exception as exc:
            offered.append({"name": node.name, "reachable": False,
                            "resources": [], "capabilities": [], "error": str(exc)})
    return jsonify(resources=_resource_view(project), nodes=offered)


def _reread_on_node(project):
    """Re-read a node-backed image under the choice just recorded.

    Quiet about a node it cannot reach. The choice is saved either way, and
    `attach_image` applies it whenever the image is next attached -- so the
    worst case is the rebuild happening later rather than the answer being
    lost, and refusing the whole edit because a laptop went to sleep would be
    the wrong trade for a control that has already done the durable half of its
    job.
    """
    from plexora import nodes as node_api

    binding = project.resource("image")
    if binding is None or not binding.is_node:
        return
    try:
        node_api.attach_image(project.name, node=binding.node,
                              resource_id=binding.resource_id)
    except Exception:
        app.logger.warning(
            "could not re-read %r on node %r under its new image type",
            project.name, binding.node, exc_info=True)


@app.route('/project/<string:name>/resources/<string:kind>', methods=['POST'])
def project_attach_resource(name, kind):
    """Point one resource at a node, or bring it back to this machine.

    `node` absent means detach, and then `path` says where the file is on THIS
    machine -- required, because a resource that was on a node has no local
    copy by construction. Detaching leaves every answer the project has
    recorded about the resource -- roles, marker split, coordinate source --
    exactly as they were, because a table that comes home is not a table that
    has to be re-imported.
    """
    from plexora import nodes as node_api

    payload = request.get_json(silent=True) or {}
    node = (payload.get("node") or "").strip()
    resource_id = (payload.get("resource_id") or "").strip()

    if Project.find(name) is None:
        return jsonify(error="Unknown project"), 404
    try:
        if not node:
            node_api.detach(name, kind, path=payload.get("path"))
        elif kind == "table":
            node_api.attach_table(name, node=node, resource_id=resource_id)
        elif kind == "image":
            node_api.attach_image(name, node=node, resource_id=resource_id)
        elif kind == "segmentation":
            node_api.attach_segmentation(name, node=node, resource_id=resource_id)
        else:
            return jsonify(error=f"Unknown resource kind: {kind}"), 400
    except KeyError as exc:
        return jsonify(error=str(exc).strip("'\"")), 400
    except ValueError as exc:
        return jsonify(error=str(exc)), 400
    except Exception as exc:
        return jsonify(error=str(exc)), 502

    return jsonify(ok=True, resources=_resource_view(Project.load(name)))


def _editable_roles(project):
    """Which roles this project's user may reassign.

    All of them, for every format. `cell_id`, `x` and `y` used to be withheld
    from AnnData and SpatialData projects because the adapter synthesizes those
    columns, so repointing the role named a column the loaded table did not
    have. They are answerable now because the answer goes into the read spec
    instead -- which is the only way to say "the mask's label values are in this
    obs column", and without it a segmentation overlay could never line up.
    """
    return list(ROLE_NAMES) if project.has_table else []


def _needs_for_tool(project, tool_name):
    """The requirements a named tool is still missing, so the edit page can
    highlight exactly those fields. This is the no-JavaScript twin of the
    requirements modal -- same question, same answer, different surface."""
    if not tool_name:
        return None
    plugin = plugin_registry.find(app, tool_name)
    if plugin is None or not plugin.requires.applies_to(project):
        return None
    return {
        "tool": plugin.name,
        "label": plugin.label,
        "missing": [r.describe() for r in plugin.requires.missing_from(project)],
        "confirm": [r.describe() for r in plugin.requires.unconfirmed_from(project)],
        "optional": [r.describe() for r in plugin.requires.optional_missing_from(project)],
    }


@app.route('/project/<string:name>', methods=['POST'])
def save_project(name):
    """Apply an edit. Everything except the image can change.

    Merge semantics throughout: a key the request does not mention is carried
    across untouched. The expensive work -- re-reading a new data file,
    converting a new mask -- runs only when that input actually changed, which
    is what makes saving an unchanged form free.
    """
    payload = request.get_json(silent=True) or {}
    project = Project.find(name)
    if project is None:
        return jsonify(success=False, error="Unknown project"), 404

    try:
        changed = _apply_edit(project, payload)
    except ValueError as exc:
        # A bad path or an unreadable file is the user's to fix, and they need
        # to be told which. The old handler returned success=False with HTTP
        # 200 and no message, and the client navigated away regardless.
        return jsonify(success=False, error=str(exc)), 400

    if changed:
        # An answer is only accepted once the file can be read with it, so a
        # role that rewrites the read spec into something the adapter refuses
        # is put back rather than left stored -- see tool_routes.
        error = tool_routes._reload_or_restore(name, project)
        if error:
            return jsonify(success=False, error=error), 400

    project = Project.find(name)
    return jsonify(success=True, reloaded=changed,
                   segmentation_pending=project.segmentation.pending)


def _apply_edit(project, payload):
    """Returns whether anything changed that needs a datasource reload."""
    from plexora.server.providers.base import is_node_locator
    from plexora.server.routes import import_routes

    changed = False

    if "segmentation" in payload:
        wanted = (payload.get("segmentation") or "").strip() or None
        # What the field was showing -- the node address when the mask is on
        # one, because that is what `_describe` put in it. Comparing against a
        # local source path instead would read every save of an unrelated
        # setting as "the user cleared the mask".
        current = _segmentation_field(project)
        if (wanted or None) != (current or None):
            if (wanted and not is_node_locator(wanted)
                    and not Path(wanted).expanduser().exists()):
                raise ValueError(f"No such segmentation mask: {wanted}")
            # Local path, node address or empty -- attach_segmentation is the
            # one place that tells them apart, for all three surfaces.
            import_routes.attach_segmentation(project.name, wanted)
            changed = True

    swapped = False
    if "data" in payload:
        wanted = (payload.get("data") or "").strip() or None
        current = project.dataset.src if project.dataset else None
        # A different path is the obvious case. The other one is a source whose
        # PATH is unchanged and whose table has just been chosen -- which is
        # the whole shape of an unresolved project, and the only edit that
        # makes it readable. Comparing paths alone dropped that answer
        # silently: the user picked a table, pressed Save, and the project went
        # on being unreadable with nothing said.
        spec = project.dataset
        narrowed = wanted and spec is not None and (
            (payload.get("table") or None) != (spec.table or None)
            or ((payload.get("subset_column") or None)
                != ((spec.subset or {}).get("column") or None)))
        if (wanted or None) != (current or None) or narrowed:
            import_routes.replace_project_data(project.name, wanted, payload)
            changed = True
            swapped = True

    # Presence, not truth, for the same reason cellLayer is read that way below:
    # "" means Automatic, which is a change worth applying.
    if "imageType" in payload:
        wanted = (payload.get("imageType") or "").strip() or None
        if wanted != project.image.image_type_choice:
            updated = Project.mutate(project.name,
                                     lambda current: current.with_image_type(wanted))
            # Re-read only when the choice actually landed. `with_image_type`
            # ignores a value it does not recognise, and re-registering on that
            # would rebuild the project to say exactly what it already said.
            if updated and updated.image.image_type_choice == wanted:
                if project.image.src:
                    reregister_image(project.name)
                    changed = True
                else:
                    # An image on a data node has no local file to re-read, but
                    # it still has to be re-READ: the two modes disagree about
                    # the layer list -- one `rgb` layer or three channels --
                    # and recording the choice without rebuilding it left the
                    # control looking like it had done nothing.
                    #
                    # `attach_image` picks the stored choice up itself, so this
                    # is the same call the Attach control makes rather than a
                    # second way of applying an override. A project whose image
                    # is neither local nor on a node has nothing to rebuild;
                    # the choice stands for the next time it acquires one.
                    _reread_on_node(updated)
                    changed = True

    # Only when the file itself did not change: replace_project_data already
    # reads `features_layer` out of this same payload, and applying it twice
    # would validate the new choice against the old file's layer list.
    if not swapped:
        changed = apply_feature_choice(project, payload) or changed

    roles = payload.get("roles")
    columns = payload.get("columns")
    coordinates = payload.get("coordinates")
    single_image = payload.get("single_image")
    row_number_ids = payload.get("row_number_ids")
    # Presence, not truth: "" is the client saying "no override, draw whatever
    # this project resolves to", which is a change worth applying and would be
    # dropped by a plain truthiness test.
    chose_layer = "cellLayer" in payload
    cell_layer = payload.get("cellLayer")
    confirm = payload.get("confirm")
    if (roles or columns or coordinates or single_image or row_number_ids
            or chose_layer or confirm):
        def _apply(current):
            if columns:
                current = current.with_columns(columns.get("markers") or [],
                                               columns.get("metadata") or [])
            # The same helper the requirements modal applies its answers with,
            # so the two surfaces cannot disagree about what a payload means.
            current = tool_routes.apply_column_answers(current, payload)
            if chose_layer:
                current = current.with_cell_layer(cell_layer)
            # Saving this page is the user looking at these values and
            # accepting them, which is exactly what the requirements modal asks
            # for -- so a tool opened afterwards must not ask again.
            return current.with_confirmed(confirm or ())

        Project.mutate(project.name, _apply)
        # A cell-layer choice on its own changes nothing the datasource holds;
        # it is read from the config by the viewer. Reloading for it would
        # re-open the image to record a preference.
        changed = changed or bool(roles or columns or coordinates
                                  or row_number_ids)

    return changed


def apply_feature_choice(project, payload):
    """Point the reader at a matrix and/or switch the log1p transform.

    Shared with the requirements modal (tool_routes), because both surfaces ask
    the same question and getting the answer to stick means the same two writes.
    Returns whether anything changed -- both halves change what every number in
    the app is, so either one needs the datasource re-read.
    """
    layer = payload.get("features_layer")
    has_log = "features_log" in payload
    log = bool(payload.get("features_log"))
    wants_layer = bool(layer) and layer != project.feature_source
    wants_log = has_log and log != project.log_transformed
    if not wants_layer and not wants_log:
        return False

    # Read outside the write lock: the layer list may come off disk, and holding
    # config.json's lock across a file read serializes every other writer behind
    # it for no reason.
    layers = source_layers(project.dataset) if wants_layer else None

    def _change(current):
        # The available list goes in first, so a project imported before it was
        # recorded validates the choice against the file rather than against an
        # empty tuple that would reject every layer.
        if wants_layer:
            current = current.with_layers(layers).with_feature_source(layer)
        if wants_log:
            current = current.with_log_transform(log)
        return current

    Project.mutate(project.name, _change)
    return True


@app.route('/project/<string:name>/delete', methods=['POST'])
def delete_project(name):
    """Remove a project and everything derived for it.

    POST, not GET: this is an irreversible rmtree, and it used to sit behind a
    link that any crawler, prefetcher or stale bookmark could follow.
    """
    project = Project.find(name)
    if project is None:
        return jsonify(success=False, error="Unknown project"), 404
    if project.is_shared:
        # A shared project belongs to whoever provisioned the root it sits on.
        # Refused here rather than allowed to fail against a read-only
        # filesystem, so the answer is a sentence rather than a traceback --
        # and so a WRITABLE shared root cannot let one user delete a project
        # every other user on the machine is working from.
        return jsonify(
            success=False,
            error="This project is on a shared data directory and cannot be "
                  "deleted from Plexora.",
        ), 403

    project.delete()
    # The grouping goes with it. Here rather than inside `Project.delete()`:
    # that primitive is also how a half-finished registration is rolled back,
    # and a rollback must not reach into a file the failed import never
    # touched.
    datasets.forget_project(name)
    # Only this user's own copy of the project directory -- which is everything
    # Plexora put under its own root, and deliberately not the label pyramid it
    # derived beside the user's mask. That file is named after the mask rather
    # than after any project, other projects and data nodes may be serving it,
    # and it sits in a directory Plexora was invited into rather than one it
    # owns. Deleting a project is not permission to delete from there.
    directory = paths.project_state_dir(name)
    if directory.is_dir():
        shutil.rmtree(directory, ignore_errors=True)
    return jsonify(success=True)
