"""One menu bar in the desktop app's window.

On Windows and Linux a native menu is drawn inside the window, as a strip
above the page, and the page's navbar is already a menu bar with the same File
/ View / Help. The shell sets no native menu there (desktop/src-tauri/src/
menu.rs), so what only the native menu carried -- New Window, Full Screen,
Interface Size, Show Data Folder, Show Logs -- lives in the navbar as
desktop-only rows that reach the shell through commands. macOS keeps its menu:
it is the system's bar along the top of the screen, not a second one inside
the window.

The pieces sit in four languages and five files, and the failure of any one is
a row that silently does nothing. These checks are the contract between them;
the bridge's behaviour is tests/js/desktop_bridge_probe.mjs's, and the Rust
half's `cargo test`.
"""

import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SHELL = REPO / "desktop" / "src-tauri"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def shell_actions() -> set[str]:
    source = read(SHELL / "src" / "commands.rs")
    match = re.search(r"SHELL_ACTIONS: &\[&str\] = &\[([^\]]*)\]", source)
    assert match, "commands.rs no longer declares SHELL_ACTIONS"
    return set(re.findall(r'"([a-z_]+)"', match.group(1)))


def row_actions() -> set[str]:
    source = read(REPO / "plexora" / "client" / "src" / "js" / "services" / "desktopBridge.js")
    match = re.search(r"const ROW_ACTIONS = \{(.*?)\};", source, re.S)
    assert match, "desktopBridge.js no longer declares ROW_ACTIONS"
    return set(re.findall(r"^\s*([a-z_]+):", match.group(1), re.M))


def test_the_native_menu_bar_is_set_on_macos_only():
    source = read(SHELL / "src" / "menu.rs")
    assert 'pub const NATIVE_MENU_BAR: bool = cfg!(target_os = "macos");' in source
    install = source[source.index("pub fn install"):]
    install = install[:install.index("\n}\n")]
    assert install.index("if !NATIVE_MENU_BAR") < install.index("app.set_menu")


def test_every_window_row_in_the_navbar_is_something_the_bridge_or_the_shell_runs():
    template = read(REPO / "plexora" / "client" / "templates" / "base.html")
    used = set(re.findall(r'data-desktop-action="([a-z_]+)"', template))
    assert used == {"new_window", "fullscreen", "zoom_in", "zoom_out", "zoom_reset",
                    "show_data", "show_logs"}
    unknown = used - row_actions() - shell_actions()
    assert not unknown, f"rows nothing runs: {unknown}"


def test_the_rows_the_documentation_names_are_there():
    """desktop-app.mdx and file-locations.mdx send people to Help -> Show Data
    Folder and Help -> Show Logs; with no native menu, these rows are them."""
    template = read(REPO / "plexora" / "client" / "templates" / "base.html")
    help_menu = template[template.index('aria-labelledby="navbarHelpDropdown"'):]
    assert "Show Data Folder" in help_menu and "Show Logs" in help_menu


def test_every_shell_action_is_handled_by_the_shell():
    menu = read(SHELL / "src" / "menu.rs")
    runner = menu[menu.index("pub fn run("):]
    for action in shell_actions():
        assert f'"{action}"' in runner, action


def test_shell_action_is_a_command_the_page_is_allowed_to_call():
    assert '"shell_action"' in read(SHELL / "build.rs")
    assert "commands::shell_action" in read(SHELL / "src" / "lib.rs")
    assert '"allow-shell-action"' in read(SHELL / "capabilities" / "main.json")
    assert (SHELL / "permissions" / "autogenerated" / "shell_action.toml").is_file()
